"""
Block Grouper.

Groups nearby OCR words and lines into cohesive logical regions or paragraphs
based on geometric proximity. No AI used; purely heuristic.
"""

from app.services.ocr.models import OCRPage
from app.services.layout.models import StructuredSection, RegionType

class BlockGrouper:
    def group(self, page: OCRPage) -> list[StructuredSection]:
        """
        Groups blocks from a page into StructuredSections.
        For this framework, we assume blocks generated by OCR have already
        been somewhat grouped. Here we map them to StructuredSections.
        """
        sections = []
        for block in page.blocks:
            words = []
            for line in block.lines:
                words.extend(line.words)
            
            # Simple heuristic: If it's a short single line, maybe a TITLE or HEADER
            # For now, default to PARAGRAPH
            region_type = RegionType.PARAGRAPH
            if len(block.lines) == 1 and len(words) < 5:
                region_type = RegionType.TITLE
                
            section = StructuredSection(
                region_type=region_type,
                text=block.text,
                words=words,
                # In a full implementation, compute the bounding box encompassing all words
                bounding_box=words[0].bounding_box if words else None
            )
            sections.append(section)
            
        return sections
