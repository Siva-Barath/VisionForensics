"""
Investigation Summary Builder.
"""
from app.services.evidence_fusion.models import FinalForensicAssessment

class InvestigationSummaryBuilder:
    def build(self, assessment: FinalForensicAssessment) -> str:
        verdict_str = assessment.verdict.name.replace("_", " ")
        risk = assessment.calibrated_risk * 100
        
        if not assessment.breakdown.contributors:
            return f"The document was analyzed and determined to be {verdict_str} with a {risk:.1f}% forgery risk. No significant structural anomalies or forensic evidence of tampering were found."
            
        strongest = max(assessment.breakdown.contributors, key=lambda c: c.risk_shift)
        
        narrative = f"The document was analyzed and returned a final verdict of {verdict_str} (Forgery Risk: {risk:.1f}%). "
        narrative += f"The strongest evidence contributing to this decision was generated by the {strongest.category} detector, "
        narrative += f"which shifted the posterior probability by {(strongest.risk_shift * 100):+.1f}%. "
        
        if assessment.recommendations:
            narrative += f"Investigators are advised to review the {len(assessment.recommendations)} generated recommendations."
            
        return narrative
